def test_generate_diet_plan(test_app, auth_headers):
    req_data = {
        "age": 25, "weight": 65, "height": 170, "gender": "female",
        "dietary_preference": "non-vegetarian", "allergies": "",
        "activity_level": "sedentary", "goal": "maintain"
    }
    response = test_app.post("/api/diet/generate", headers=auth_headers, json=req_data)
    assert response.status_code == 201
    data = response.json()
    assert "meals" in data
    assert "total_calories" in data
    
