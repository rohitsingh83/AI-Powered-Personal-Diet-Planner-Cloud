def test_get_plan_by_id(test_app, auth_headers):
    req_data = {
        "age": 30, "weight": 80, "height": 180, "gender": "male",
        "dietary_preference": "vegetarian", "allergies": "",
        "activity_level": "moderate", "goal": "muscle gain"
    }
    gen_response = test_app.post("/api/diet/generate", headers=auth_headers, json=req_data)
    plan_id = gen_response.json()["id"]

    response = test_app.get(f"/api/diet/plans/{plan_id}", headers=auth_headers)
    assert response.status_code == 200
    assert response.json()["id"] == plan_id

